fn extension_to_json(e: &extension::Extension) -> Value {
    json!({
        "extension_kind": e.extension_kind.as_ref().map(enum_json),
        // Opaque payload -- hex-encoded rather than pulling in a base64 dep
        // for a field Phase 75 does not need to interpret.
        "data": e.data.as_deref().map(hex_encode),
    })
}

