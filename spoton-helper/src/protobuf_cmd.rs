#[cfg(test)]
mod tests {
    use super::*;
    use protobuf::MessageField;

    #[test]
    fn collection_v2_decode_roundtrip() {
        let mut item = collection2v2::CollectionItem::new();
        item.uri = "spotify:track:abc".to_string();
        item.added_at = 1_700_000_000;
        item.is_removed = true;

        let mut resp = collection2v2::PageResponse::new();
        resp.items.push(item);
        resp.next_page_token = "next".to_string();
        let bytes = resp.write_to_bytes().expect("encode fixture");

        let json = decode_collection_v2(&bytes).expect("decode");
        assert_eq!(json["items"][0]["uri"], "spotify:track:abc");
        assert_eq!(json["items"][0]["added_at"], 1_700_000_000);
        assert_eq!(json["items"][0]["is_removed"], true);
        assert_eq!(json["next_page_token"], "next");
    }

    #[test]
    fn collection_v2_encode_roundtrip() {
        let request_json = json!({
            "username": "alice",
            "set": "starred",
            "pagination_token": "tok",
            "limit": 50,
        });
        let input = serde_json::to_vec(&request_json).expect("serialize fixture");

        let encoded = encode_collection_v2(&input).expect("encode");
        let parsed =
            collection2v2::PageRequest::parse_from_bytes(&encoded).expect("parse back");

        assert_eq!(parsed.username, "alice");
        assert_eq!(parsed.set, "starred");
        assert_eq!(parsed.pagination_token, "tok");
        assert_eq!(parsed.limit, 50);
    }

    #[test]
    fn recently_played_decode_roundtrip() {
        let mut ctx = recently_played_backend::Context::new();
        ctx.uri = Some("spotify:track:xyz".to_string());
        ctx.lastPlayedTime = Some(123_456_789);

        let mut msg = recently_played_backend::RecentlyPlayed::new();
        msg.contexts.push(ctx);
        msg.offset = Some(0);
        msg.total = Some(1);
        let bytes = msg.write_to_bytes().expect("encode fixture");

        let json = decode_recently_played(&bytes).expect("decode");
        assert_eq!(json["contexts"][0]["uri"], "spotify:track:xyz");
        assert_eq!(json["contexts"][0]["lastPlayedTime"], 123_456_789);
        assert_eq!(json["total"], 1);
    }

    #[test]
    fn rootlist_decode_roundtrip() {
        let mut playlist = rootlist_request::Playlist::new();
        playlist.row_id = Some("row-1".to_string());

        let mut item = rootlist_request::Item::new();
        item.playlist = MessageField::some(playlist);

        let mut folder = rootlist_request::Folder::new();
        folder.item.push(item);
        folder.row_id = Some("folder-root".to_string());

        let mut resp = rootlist_request::Response::new();
        resp.root = MessageField::some(folder);
        let bytes = resp.write_to_bytes().expect("encode fixture");

        let json = decode_rootlist(&bytes).expect("decode");
        assert_eq!(json["root"]["row_id"], "folder-root");
        assert_eq!(json["root"]["item"][0]["playlist"]["row_id"], "row-1");
    }

    #[test]
    fn recently_played_encode_is_decode_only() {
        let err = process("recently-played", "encode", b"{}").unwrap_err();
        assert!(err.to_string().contains("decode-only"));
    }

    #[test]
    fn rootlist_encode_is_decode_only() {
        let err = process("rootlist", "encode", b"{}").unwrap_err();
        assert!(err.to_string().contains("decode-only"));
    }

    #[test]
    fn malformed_protobuf_returns_error_not_panic() {
        let bogus = vec![0xFF, 0x00, 0xAB, 0xCD, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF];
        let result = decode_collection_v2(&bogus);
        assert!(result.is_err());
    }

    #[test]
    fn malformed_json_returns_error_not_panic() {
        let result = encode_collection_v2(b"{not valid json");
        assert!(result.is_err());
    }

    #[test]
    fn oversized_input_is_rejected() {
        let big = vec![0u8; MAX_STDIN_BYTES + 1];
        let result = read_bounded(std::io::Cursor::new(big));
        assert!(result.is_err());
    }

    #[test]
    fn unknown_schema_lists_supported_schemas() {
        let err = process("bogus-schema", "decode", b"").unwrap_err();
        let msg = err.to_string();
        assert!(msg.contains("collection-v2"));
        assert!(msg.contains("recently-played"));
        assert!(msg.contains("rootlist"));
    }
}
