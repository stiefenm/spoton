//! `protobuf` subcommand -- stdin/stdout protobuf <-> JSON conversion (D-02).
//!
//! Covers all three D-02 schemas: collection/v2 (`PageRequest`/`PageResponse`),
//! recently-played (the backend `RecentlyPlayed` wrapper), and rootlist
//! (`Response` and its full folder/playlist tree). `decode` reads raw
//! protobuf bytes from stdin and emits JSON on stdout; `encode` is
//! supported only for collection-v2 (the only schema with a request
//! message upstream) and reads JSON from stdin, emitting protobuf bytes on
//! stdout.
//!
//! Untrusted stdin is bounded (`MAX_STDIN_BYTES`) and decoded via the
//! generated types' safe `protobuf::Message` API -- no `unsafe`, no manual
//! varint/pointer math (RESEARCH.md T-74-08). Any parse failure returns an
//! `Err`; `main.rs` turns that into a single-line JSON error object on
//! stdout and a non-zero exit (RESEARCH.md T-74-07) -- this module never
//! panics or unwraps on data that came from stdin.

use anyhow::{bail, Context, Result};
use protobuf::{EnumOrUnknown, Message};
use serde_json::{json, Value};
use std::io::{Read, Write};

// Generated by build.rs (`protobuf_codegen::Codegen` `.pure()` path) from
// the vendored `proto/` schemas -- see build.rs for the exact input list.
mod protos {
    include!(concat!(env!("OUT_DIR"), "/protos/mod.rs"));
}

